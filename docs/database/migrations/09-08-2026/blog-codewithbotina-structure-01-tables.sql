CREATE VIEW public.mismatched_poll_translations WITH (security_invoker='on') AS
 WITH option_counts AS (
         SELECT poll_options.poll_id,
            (count(*))::integer AS option_count
           FROM public.poll_options
          GROUP BY poll_options.poll_id
        )
 SELECT p1.id AS poll_1_id,
    p1.slug AS poll_1_slug,
    p1.language AS poll_1_lang,
    p1.type,
    COALESCE(oc1.option_count, 0) AS poll_1_option_count,
    p2.id AS poll_2_id,
    p2.slug AS poll_2_slug,
    p2.language AS poll_2_lang,
    COALESCE(oc2.option_count, 0) AS poll_2_option_count
   FROM (((public.polls p1
     JOIN public.polls p2 ON ((p1.translation_group_id = p2.translation_group_id)))
     LEFT JOIN option_counts oc1 ON ((oc1.poll_id = p1.id)))
     LEFT JOIN option_counts oc2 ON ((oc2.poll_id = p2.id)))
  WHERE ((p1.id < p2.id) AND (p1.translation_group_id IS NOT NULL) AND ((p1.type)::text = ANY ((ARRAY['single_choice'::character varying, 'multiple_choice'::character varying])::text[])) AND ((p2.type)::text = ANY ((ARRAY['single_choice'::character varying, 'multiple_choice'::character varying])::text[])) AND (COALESCE(oc1.option_count, 0) <> COALESCE(oc2.option_count, 0)));


