--

CREATE FUNCTION public.delete_user_account(target_user_id uuid) RETURNS void
    LANGUAGE plpgsql SECURITY DEFINER
    SET search_path TO 'public', 'auth'
    AS $_$
BEGIN
  -- Manual deletions (for explicit control and clarity).
  -- Use ::text comparisons to tolerate environments where user_id columns were created as VARCHAR/TEXT.
  DELETE FROM public.comments WHERE user_id::text = target_user_id::text;
  DELETE FROM public.post_reactions WHERE user_id::text = target_user_id::text;
  DELETE FROM public.admin_users WHERE user_id::text = target_user_id::text;

  -- Optional tables: keep the function safe across environments.
  IF to_regclass('public.user_sessions') IS NOT NULL THEN
    EXECUTE 'DELETE FROM public.user_sessions WHERE user_id::text = $1::text' USING target_user_id;
  END IF;

  -- Supabase Auth tables may vary; attempt cleanup if present.
  IF to_regclass('auth.sessions') IS NOT NULL THEN
    EXECUTE 'DELETE FROM auth.sessions WHERE user_id::text = $1::text' USING target_user_id;
  END IF;

  IF to_regclass('auth.refresh_tokens') IS NOT NULL THEN
    EXECUTE 'DELETE FROM auth.refresh_tokens WHERE user_id::text = $1::text' USING target_user_id;
  END IF;

  -- Finally delete the auth user (cascades to public.users and any FK dependencies).
  DELETE FROM auth.users WHERE id::text = target_user_id::text;
END;
$_$;


--
-- Name: enforce_poll_translation_type_match(); Type: FUNCTION; Schema: public; Owner: -
--

CREATE FUNCTION public.enforce_poll_translation_type_match() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
DECLARE
  expected_type text;
BEGIN
  IF NEW.translation_group_id IS NULL THEN
    RETURN NEW;
  END IF;

  SELECT type INTO expected_type
  FROM public.polls
  WHERE id = NEW.translation_group_id;

  IF expected_type IS NULL THEN
    RETURN NEW;
  END IF;

  IF NEW.type <> expected_type THEN
    RAISE EXCEPTION 'Cannot link polls of different types: % != %', NEW.type, expected_type
      USING ERRCODE = '23514';
  END IF;

  IF EXISTS (
    SELECT 1
    FROM public.polls p
    WHERE p.translation_group_id = NEW.translation_group_id
      AND p.id <> NEW.id
      AND p.type <> NEW.type
  ) THEN
    RAISE EXCEPTION 'Cannot link polls of different types in translation group %', NEW.translation_group_id
      USING ERRCODE = '23514';
  END IF;

  RETURN NEW;
END;
$$;


